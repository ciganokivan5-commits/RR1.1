#include <stdio.h>
#include <windows.h> // Потрібно для SetConsoleOutputCP та SetConsoleCP
/**
 * @return int Код завершення програми (0 - успішно).
 */
int main(void) {
    // Встановлюємо кодування UTF-8 для вводу та виводу в консолі Windows
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Встановлення української локалізації для коректного виведення в консоль
    // (залежно від середовища розробки можна адаптувати)

    double a = 0.0;     // Основа степеня (може бути дійсним числом)[cite: 1]
    int N = 0;          // Кінцева межа суми та показник степеня (ціле невід'ємне число)[cite: 1]
    double term = 1.0;  // Змінна для накопичення результату піднесення до степеня (a^(N-1))
    long long sum_n = 0;// Змінна для обчислення арифметичної суми від 1 до N
    double S = 0.0;     // Кінцевий результат розрахунку суми ряду[cite: 1]

    // Запит та зчитування вхідних даних від користувача[cite: 1]
    printf("Введіть значення дійсного числа a: ");
    if (scanf("%lf", &a) != 1) {
        fprintf(stderr, "Помилка: некоректне введення значення 'a'.\n");
        return 1;
    }

    printf("Введіть значення цілого невід'ємного числа N (N >= 0): ");
    if (scanf("%d", &N) != 1 || N < 0) {
        fprintf(stderr, "Помилка: N має бути цілим числом, більшим або рівним 0.\n");
        return 1;
    }

    /*
     * 1. Обчислення степеня a^(N-1) без використання функції pow().
     * Особливі випадки:
     * - Якщо N = 0, то степінь дорівнює a^(-1) = 1 / a (за умови, що a != 0).
     * - Якщо N = 1, то a^(1-1) = a^0 = 1.
     */
    if (N == 0) {
        if (a == 0.0) {
            fprintf(stderr, "Помилка: ділення на нуль при обчисленні a^(-1).\n");
            return 1;
        }
        term = 1.0 / a;
    } else {
        // Послідовне множення для обчислення a^(N-1)
        for (int i = 0; i < (N - 1); i++) {
            term *= a;
        }
    }

    /*
     * 2. Обчислення суми ряду від n = 1 до N: sum_{n=1}^{N} n.
     * Використовуємо звичайний цикл накопичення суми.
     */
    for (int n = 1; n <= N; n++) {
        sum_n += n;
    }

    /*
     * 3. Формування загального результату S.
     * S = a^(N-1) + sum(n)[cite: 1]
     */
    S = term + (double)sum_n;

    // Виведення результатів обчислень на екран
    printf("\n--- Результати обчислень ---\n");
    printf("Параметр a = %.4f\n", a);
    printf("Параметр N = %d\n", N);
    printf("Доданок 1 (a^(N-1)) = %.4f\n", term);
    printf("Доданок 2 (сума від 1 до N) = %lld\n", sum_n);
    printf("Загальна сума ряду S = %.4f\n", S);

    return 0;
}
